"""Generate every app icon from ONE geometry definition.

Writes (paths relative to the repo root):
  mobile/android/.../res/drawable/ic_launcher_background.xml   vector, brand gradient
  mobile/android/.../res/drawable/ic_launcher_foreground.xml   vector, ledger + coin
  mobile/android/.../res/drawable/ic_launcher_monochrome.xml   Android 13+ themed icon
  mobile/android/.../res/mipmap-anydpi-v26/ic_launcher(_round).xml
  mobile/android/.../res/mipmap-*/ic_launcher(_round).png      Android 7 fallbacks
  mobile/android/.../res/drawable*/splash.png                  dark branded splash
  icons/                                                        web favicon + touch icons

Run from anywhere:  python mobile/scripts/make-icons.py   (needs Pillow)
The design lives in a 108x108 adaptive-icon canvas. Everything is scaled about the
centre so it stays inside the 66dp circular safe zone (no launcher mask clips it).
"""
import math
import os
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
RES = os.path.join(ROOT, 'mobile', 'android', 'app', 'src', 'main', 'res')
WEB = os.path.join(ROOT, 'icons')
APP_BG = '#030712'                                   # page background (styles/app.css)
GRAD = [('#6366F1', 0.0), ('#7C3AED', 0.55), ('#A855F7', 1.0)]  # header logo gradient
S, C = 0.82, 54.0                                    # composition scale about the centre


def t(v):  # canvas coordinate -> scaled coordinate
    return C + (v - C) * S


# ---- design (unscaled 108-unit canvas) -------------------------------------------
# kind, geometry, fill, monochrome role ('solid' | 'hole' | None)
SHAPES = [
    ('rrect', (35.5, 30.5, 40, 50, 5), '#1E1B4B55', None),        # book drop shadow
    ('rrect', (33, 28, 40, 50, 5), '#FFFFFF', 'solid'),            # cover / page
    ('rrect', (33, 28, 12, 50, 5), '#C7D2FE', None),               # spine (rounded left)
    ('rect', (39, 28, 6, 50), '#C7D2FE', None),                    # spine (square right)
] + [
    ('circle', (45, y, 2.3), '#4F46E5', 'hole') for y in (36, 46, 56, 66)  # binder rings
] + [
    ('rrect', (50, 35, 17, 4.2, 2.1), '#4F46E5', 'hole'),           # header bar
] + [
    s for y in (44.5, 51.5, 58.5) for s in (
        ('rrect', (50, y, 9.5, 2.6, 1.3), '#A5B4FC', 'hole'),      # description column
        ('rrect', (61.5, y, 5.5, 2.6, 1.3), '#6366F1', 'hole'),    # amount column
    )
] + [
    ('circle', (73.2, 74.2, 11.5), '#1E1B4B55', None),             # coin shadow
    ('circle', (72, 73, 11.5), '#F59E0B', 'solid'),                # coin rim
    ('circle', (72, 73, 9), '#FBBF24', None),                      # coin face
    ('poly', [(66.6, 74.2), (72, 67.6), (77.4, 74.2), (74.2, 74.2),  # cashback up-arrow
              (74.2, 78.6), (69.8, 78.6), (69.8, 74.2)], '#FFFFFF', 'hole'),
]


# ---- vector drawables --------------------------------------------------------------
def f(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def rrect_path(x, y, w, h, r):
    x, y, w, h, r = t(x), t(y), w * S, h * S, r * S
    return (f'M{f(x + r)},{f(y)}H{f(x + w - r)}A{f(r)},{f(r)} 0 0 1 {f(x + w)},{f(y + r)}'
            f'V{f(y + h - r)}A{f(r)},{f(r)} 0 0 1 {f(x + w - r)},{f(y + h)}'
            f'H{f(x + r)}A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y + h - r)}'
            f'V{f(y + r)}A{f(r)},{f(r)} 0 0 1 {f(x + r)},{f(y)}Z')


def shape_path(kind, g):
    if kind == 'rrect':
        return rrect_path(*g)
    if kind == 'rect':
        x, y, w, h = g
        return rrect_path(x, y, w, h, 0.001)
    if kind == 'circle':
        cx, cy, r = t(g[0]), t(g[1]), g[2] * S
        return f'M{f(cx - r)},{f(cy)}a{f(r)},{f(r)} 0 1 0 {f(2 * r)},0a{f(r)},{f(r)} 0 1 0 {f(-2 * r)},0Z'
    if kind == 'poly':
        pts = [(t(x), t(y)) for x, y in g]
        return 'M' + 'L'.join(f'{f(x)},{f(y)}' for x, y in pts) + 'Z'


def android_color(hexstr):  # #RRGGBBAA -> #AARRGGBB
    h = hexstr.lstrip('#')
    return '#' + (h[6:8] + h[:6] if len(h) == 8 else h)


VEC_HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by mobile/scripts/make-icons.py - edit the script, not this file. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n')


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)


def vectors():
    stops = ''.join(f'                <item android:offset="{o}" android:color="{c}"/>\n' for c, o in GRAD)
    write(os.path.join(RES, 'drawable', 'ic_launcher_background.xml'), VEC_HEAD +
          '    <path android:pathData="M0,0h108v108h-108z">\n'
          '        <aapt:attr name="android:fillColor">\n'
          '            <gradient android:type="linear" android:startX="0" android:startY="0"\n'
          '                android:endX="108" android:endY="108">\n' + stops +
          '            </gradient>\n        </aapt:attr>\n    </path>\n'
          # soft top-left sheen for depth
          '    <path android:pathData="M0,0h108v46c-30,-14 -70,-6 -108,14z" android:fillColor="#14FFFFFF"/>\n'
          '</vector>\n')

    fg = ''.join(f'    <path android:fillColor="{android_color(c)}" android:pathData="{shape_path(k, g)}"/>\n'
                 for k, g, c, _ in SHAPES)
    write(os.path.join(RES, 'drawable', 'ic_launcher_foreground.xml'), VEC_HEAD + fg + '</vector>\n')

    # Monochrome (themed icons): only alpha matters, so cut the ledger detail out of
    # the solid silhouettes with even-odd holes. Book holes go in the book path,
    # coin holes (the arrow) in the coin path.
    book = [shape_path(k, g) for k, g, _, role in SHAPES[:8] if role in ('solid', 'hole')]
    book += [shape_path(k, g) for k, g, _, role in SHAPES[8:-4] if role == 'hole']
    coin = [shape_path(k, g) for k, g, _, role in SHAPES[-4:] if role in ('solid', 'hole')]
    mono = ''.join(f'    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{"".join(p)}"/>\n'
                   for p in (book, coin))
    write(os.path.join(RES, 'drawable', 'ic_launcher_monochrome.xml'), VEC_HEAD + mono + '</vector>\n')

    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
                '</adaptive-icon>\n')
    for name in ('ic_launcher', 'ic_launcher_round'):
        write(os.path.join(RES, 'mipmap-anydpi-v26', name + '.xml'), adaptive)


# ---- raster rendering (fallback icons, splash, web) ---------------------------------
def rgba(hexstr):
    h = hexstr.lstrip('#')
    vals = [int(h[i:i + 2], 16) for i in range(0, len(h), 2)]
    return tuple(vals + [255] * (4 - len(vals)))


def gradient(px):
    """Diagonal 3-stop brand gradient, px x px."""
    vert = Image.linear_gradient('L').resize((px, px))           # 0 at top -> 255 at bottom
    ramp = Image.blend(vert, vert.transpose(Image.Transpose.TRANSPOSE), 0.5)  # (x+y)/2: TL -> BR
    out = Image.new('RGBA', (px, px), rgba(GRAD[0][0]))
    for (c0, o0), (c1, o1) in zip(GRAD, GRAD[1:]):
        lo, hi = int(o0 * 255), int(o1 * 255)
        band = ramp.point(lambda v, lo=lo, hi=hi: 0 if v <= lo else 255 if v >= hi else int((v - lo) * 255 / (hi - lo)))
        mixed = Image.composite(Image.new('RGBA', (px, px), rgba(c1)), Image.new('RGBA', (px, px), rgba(c0)), band)
        out = Image.composite(mixed, out, ramp.point(lambda v, lo=lo: 255 if v >= lo else 0))
    return out


def render_icon(px, shape='square'):
    """Full icon (background + foreground) at px, masked to the given launcher shape."""
    k = 4                                  # supersample
    out_n = px * k
    # Show the middle 72 of the 108-unit canvas, as Android does for adaptive icons.
    n = round(out_n * 108 / 72)
    u = n / 108.0
    img = gradient(n)
    sheen = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    ImageDraw.Draw(sheen).pieslice((-0.6 * n, -1.15 * n, 1.6 * n, 0.45 * n), 0, 180, fill=(255, 255, 255, 20))
    img = Image.alpha_composite(img, sheen)

    for kind, g, col, _ in SHAPES:
        layer = Image.new('RGBA', (n, n), (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        fill = rgba(col)
        if kind in ('rrect', 'rect'):
            x, y, w, h = g[:4]
            r = g[4] * S * u if kind == 'rrect' else 0
            d.rounded_rectangle((t(x) * u, t(y) * u, t(x + w) * u, t(y + h) * u), radius=r, fill=fill)
        elif kind == 'circle':
            cx, cy, r = t(g[0]) * u, t(g[1]) * u, g[2] * S * u
            d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=fill)
        else:
            d.polygon([(t(x) * u, t(y) * u) for x, y in g], fill=fill)
        if fill[3] < 255:                  # shadows: soften
            layer = layer.filter(ImageFilter.GaussianBlur(1.2 * u))
        img = Image.alpha_composite(img, layer)

    off = (n - out_n) // 2
    img = img.crop((off, off, off + out_n, off + out_n))
    n = out_n
    mask = Image.new('L', (n, n), 0)
    md = ImageDraw.Draw(mask)
    if shape == 'circle':
        md.ellipse((0, 0, n - 1, n - 1), fill=255)
    elif shape == 'square':                # legacy launcher: rounded square with margin
        m = n * 0.04
        md.rounded_rectangle((m, m, n - m, n - m), radius=n * 0.22, fill=255)
    else:                                  # full bleed (web touch icons)
        md.rectangle((0, 0, n, n), fill=255)
    img.putalpha(Image.composite(img.getchannel('A'), Image.new('L', (n, n), 0), mask))
    return img.resize((px, px), Image.LANCZOS)


def legacy_mipmaps():
    for dens, px in (('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)):
        d = os.path.join(RES, f'mipmap-{dens}')
        render_icon(px, 'square').save(os.path.join(d, 'ic_launcher.png'))
        render_icon(px, 'circle').save(os.path.join(d, 'ic_launcher_round.png'))
        stale = os.path.join(d, 'ic_launcher_foreground.png')  # replaced by the vector
        if os.path.exists(stale):
            os.remove(stale)


def font(size, bold=True):
    for name in (('segoeuib.ttf', 'arialbd.ttf') if bold else ('segoeui.ttf', 'arial.ttf')):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            pass
    return ImageFont.load_default()


def splashes():
    for root, _, files in os.walk(RES):
        if 'splash.png' not in files:
            continue
        path = os.path.join(root, 'splash.png')
        w, h = Image.open(path).size
        img = Image.new('RGBA', (w, h), rgba(APP_BG))
        side = int(min(w, h) * 0.30)
        icon = render_icon(side, 'square')
        title_px = max(12, int(side * 0.16))
        sub_px = max(9, int(side * 0.085))
        gap = int(side * 0.12)
        block = side + gap + title_px + int(sub_px * 1.9)
        top = (h - block) // 2
        img.alpha_composite(icon, ((w - side) // 2, top))
        d = ImageDraw.Draw(img)
        y = top + side + gap
        d.text((w / 2, y), 'CC Cashback & SSPN', font=font(title_px), fill=rgba('#F3F4F6'), anchor='mt')
        d.text((w / 2, y + title_px * 1.35), 'WALLET  ·  LEDGER  ·  SYNC', font=font(sub_px, False), fill=rgba('#818CF8'), anchor='mt')
        img.convert('RGB').save(path)


def web_icons():
    os.makedirs(WEB, exist_ok=True)
    render_icon(512, 'full').save(os.path.join(WEB, 'icon-512.png'))
    render_icon(192, 'full').save(os.path.join(WEB, 'icon-192.png'))
    render_icon(180, 'full').save(os.path.join(WEB, 'apple-touch-icon.png'))
    render_icon(64, 'square').save(os.path.join(WEB, 'favicon-64.png'))


if __name__ == '__main__':
    vectors()
    legacy_mipmaps()
    splashes()
    web_icons()
    print('icons written')
